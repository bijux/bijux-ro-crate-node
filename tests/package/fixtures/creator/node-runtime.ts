import assert from 'node:assert/strict'
import {applyChange, createDraft, inspectIncomingReferences, importCrate, materializeDraft, encodeDraft, decodeDraft, createHistory, applyHistoryChanges, inspectHistory, undo, redo} from '@bijux/ro-crate-creator'
const added = applyChange(createDraft(), {type: 'add-study'})
assert.equal(added.status, 'applied')
if (added.status !== 'applied') throw Error('study missing')
const changed = applyChange(added.draft, {type: 'set-field', entityId: added.entityId, field: 'name', value: 'Installed study'})
if (changed.status !== 'applied') throw Error('edit failed')
const output = materializeDraft(changed.draft)
if (output.status !== 'materialized') throw Error('export failed')
assert.equal(JSON.parse(output.files.get('ro-crate-metadata.json') as string)['@graph'][1].name, 'Installed study')

const specimen = applyChange(changed.draft, {type: 'add-entity', kind: 'specimen'})
if (specimen.status !== 'applied') throw Error('specimen missing')
const preparation = applyChange(specimen.draft, {type: 'add-entity', kind: 'preparation-protocol'})
if (preparation.status !== 'applied') throw Error('preparation missing')
const linked = applyChange(preparation.draft, {type: 'add-reference', sourceId: specimen.entityId, relationship: 'imagingPreparationProtocol', targetId: preparation.entityId})
if (linked.status !== 'applied') throw Error('reference missing')
assert.deepEqual(inspectIncomingReferences(linked.draft, preparation.entityId), [{sourceId: specimen.entityId, relationship: 'imagingPreparationProtocol'}])
const dataset = applyChange(linked.draft, {type: 'add-entity', kind: 'dataset'})
if (dataset.status !== 'applied') throw Error('dataset missing')
const file = applyChange(dataset.draft, {type: 'add-file', file: {path: 'Images/α.tif', size: '9007199254740993', datasetId: dataset.entityId, specimenId: specimen.entityId, type: 'image'}})
if (file.status !== 'applied') throw Error('file missing')
const manifest = materializeDraft(file.draft)
if (manifest.status !== 'materialized') throw Error('manifest missing')
assert.match(manifest.files.get('file_list.tsv') as string, /Images\/α.tif\t9007199254740993\t/)

const imported = await importCrate(manifest.files, {metadataPaths: ['ro-crate-metadata.json', 'file_list.tsv']})
assert.equal(imported.status, 'editable')
if (imported.status !== 'editable') throw Error('import failed')
assert.equal(imported.excludedPaths.length, 0)

const restored = await decodeDraft(encodeDraft(imported.draft))
if (restored.status !== 'decoded') throw Error('backup decode failed')
assert.deepEqual(inspectIncomingReferences(restored.draft, preparation.entityId), [{sourceId: specimen.entityId, relationship: 'imagingPreparationProtocol'}])

const history = createHistory(restored.draft, {limit: 2})
const updated = applyHistoryChanges(history, [{type:'set-field', entityId:'./', field:'name', value:'Changed'}, {type:'set-field', entityId:'./', field:'description', value:'Description'}])
if (updated.status !== 'applied') throw Error('batch failed')
const undone = undo(updated.history)
if (undone.status !== 'applied') throw Error('undo failed')
const redone = redo(undone.history)
if (redone.status !== 'applied' || inspectHistory(redone.history).undoCount !== 1) throw Error('redo failed')

const author = applyChange(restored.draft, {type:'add-entity',kind:'contributor'})
if (author.status !== 'applied') throw Error('author missing')
const linkedAuthor = applyChange(author.draft,{type:'add-reference',sourceId:'./',relationship:'author',targetId:author.entityId})
if (linkedAuthor.status !== 'applied') throw Error('author link missing')
const reopened = await decodeDraft(encodeDraft(linkedAuthor.draft))
if (reopened.status !== 'decoded') throw Error('author backup failed')
assert.deepEqual(inspectIncomingReferences(reopened.draft,author.entityId),[{sourceId:'./',relationship:'author'}])
