import {applyChange, createDraft, importCrate, materializeDraft, encodeDraft, decodeDraft, createHistory, applyHistoryChanges, inspectHistory, undo, redo} from '@bijux/ro-crate-creator'
const added = applyChange(createDraft(), {type: 'add-study'})
if (added.status !== 'applied') throw Error('study missing')
const edited = applyChange(added.draft, {type: 'set-field', entityId: added.entityId, field: 'name', value: 'Browser study'})
if (edited.status !== 'applied') throw Error('edit failed')
const specimen = applyChange(edited.draft, {type: 'add-entity', kind: 'specimen'})
if (specimen.status !== 'applied') throw Error('specimen missing')
const dataset = applyChange(specimen.draft, {type: 'add-entity', kind: 'dataset'})
if (dataset.status !== 'applied') throw Error('dataset missing')
const file = applyChange(dataset.draft, {type: 'add-file', file: {path: 'Images/α.tif', size: '9007199254740993', datasetId: dataset.entityId, specimenId: specimen.entityId, type: 'image'}})
if (file.status !== 'applied') throw Error('file missing')
const result = materializeDraft(file.draft)
if (result.status !== 'materialized') throw Error('export failed')
if (!(result.files.get('file_list.tsv') as string).includes('Images/α.tif\t9007199254740993')) throw Error('manifest row missing')
const imported = await importCrate(result.files, {metadataPaths:['ro-crate-metadata.json', 'file_list.tsv']})
if (imported.status !== 'editable') throw Error('browser import failed')
const restored = await decodeDraft(encodeDraft(imported.draft))
if (restored.status !== 'decoded') throw Error('browser backup decode failed')
const author = applyChange(restored.draft, {type:'add-entity',kind:'contributor'})
if (author.status !== 'applied') throw Error('browser author missing')
const linked = applyChange(author.draft, {type:'add-reference',sourceId:'./',relationship:'author',targetId:author.entityId})
if (linked.status !== 'applied') throw Error('browser author link missing')
const reopened = await decodeDraft(encodeDraft(linked.draft))
if (reopened.status !== 'decoded') throw Error('browser author backup failed')
const restoredFiles = materializeDraft(reopened.draft)
if (restoredFiles.status !== 'materialized' || !restoredFiles.files.has('file_list.tsv')) throw Error('browser backup manifest missing')
const history = createHistory(restored.draft)
const batch = applyHistoryChanges(history, [{type:'set-field', entityId:'./', field:'name', value:'Changed'}])
if (batch.status !== 'applied') throw Error('browser batch failed')
const undone = undo(batch.history)
if (undone.status !== 'applied') throw Error('browser undo failed')
const redone = redo(undone.history)
if (redone.status !== 'applied' || inspectHistory(redone.history).undoCount !== 1) throw Error('browser redo failed')
document.body.textContent = result.files.get('ro-crate-metadata.json') as string
