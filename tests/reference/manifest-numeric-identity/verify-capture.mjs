import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {portableCase} from '../../parity/normalize.mjs';
import {assertInputBytes} from '../../parity/inputs.mjs';
const [capturePath, arithmeticPath, ...extra] = process.argv.slice(2);
assert.ok(capturePath && arithmeticPath && !extra.length, 'Expected full capture and independently observed arithmetic receipt');
const input = JSON.parse(await readFile(new URL('./inputs.json', import.meta.url)));
const expected = JSON.parse(await readFile(new URL('./arm-python.json', import.meta.url)));
const raw = JSON.parse(await readFile(capturePath));
const arithmetic = JSON.parse(await readFile(arithmeticPath));
assert.equal(arithmetic.profile, 'fused', 'The retained whole-parser receipt characterizes the fused pandas build');
assert.equal(arithmetic.pandas, expected.versions.pandas);
assert.equal(arithmetic.python, expected.python);
assert.deepEqual(arithmetic.c_profiles_verified, ['separate', 'fused']);
assert.equal(raw.corpus_sha256, createHash('sha256').update(JSON.stringify(input.cases)).digest('hex'));
assert.equal(raw.cases.length, input.cases.length);
for (const item of input.cases) assertInputBytes(item, raw.cases.find(row => row.name === item.name));
const {imported_module: _module, ...portable} = raw;
portable.cases = raw.cases.map(portableCase);
assert.deepEqual(portable, expected);
console.log(input.cases.length + ' original fused-build parser outcomes independently recaptured');
