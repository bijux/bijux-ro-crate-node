import assert from 'node:assert/strict'
import {spawnSync} from 'node:child_process'
import {cp, mkdir, mkdtemp, rename, rm, symlink, writeFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {test, type TestContext} from 'node:test'
import {fileURLToPath} from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
async function fixture(t: TestContext) {
  const owner = resolve(root, 'artifacts/work')
  await mkdir(owner, {recursive: true})
  const directory = await mkdtemp(resolve(owner, 'compiler-contract-'))
  t.after(() => rm(directory, {recursive: true, force: true}))
  await symlink(resolve(root, 'node_modules'), resolve(directory, 'node_modules'), 'dir')
  return directory
}
const run = (directory: string, script: string, ...args: string[]) =>
  spawnSync(process.execPath, args.length ? ['--import', 'tsx', script, ...args] : [script], {cwd: directory, encoding: 'utf8'})

test('package compiler registration checks every owned source and rejects real type errors', async t => {
  const directory = await fixture(t)
  await mkdir(resolve(directory, 'scripts'), {recursive: true})
  for (const name of ['workspaces.mjs', 'typecheck.mjs']) await cp(resolve(root, 'scripts', name), resolve(directory, 'scripts', name))
  const pkg = resolve(directory, 'packages/catalog')
  await mkdir(resolve(pkg, 'src'), {recursive: true})
  await writeFile(resolve(pkg, 'package.json'), JSON.stringify({name: '@fixture/catalog', version: '1.0.0', type: 'module', exports: {'.': {types: './dist/index.d.ts', import: './dist/index.js'}}, scripts: {test: 'node --test'}, bijux: {declarations: 'tsconfig.json', typecheck: ['tsconfig.json'], standaloneEntries: []}}))
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const value: string = 1\n')
  const compiler = resolve(directory, 'scripts/typecheck.mjs')
  for (const options of [{noCheck: true}, {strict: false}, {strictNullChecks: false}, {noImplicitAny: false}, {skipLibCheck: true}]) {
    await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, module: 'NodeNext', target: 'ES2022', types: [], ...options}, files: ['src/index.ts']}))
    const weakened = run(directory, compiler)
    assert.notEqual(weakened.status, 0)
    assert.match(weakened.stderr, /Package compiler project must enable strict typechecking/)
  }
  await writeFile(resolve(pkg, 'base.json'), JSON.stringify({compilerOptions: {strict: true, noCheck: true}}))
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({extends: './base.json', compilerOptions: {noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  const inherited = run(directory, compiler)
  assert.notEqual(inherited.status, 0)
  assert.match(inherited.stderr, /Package compiler project must enable strict typechecking/)
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  const base = resolve(pkg, 'tsconfig.base.json')
  const shared = resolve(pkg, 'tsconfig.shared.json')
  await writeFile(shared, JSON.stringify({compilerOptions: {strict: true}}))
  await writeFile(base, JSON.stringify({extends: './tsconfig.shared.json'}))
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({extends: './tsconfig.base.json', compilerOptions: {noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  const inheritedBase = run(directory, compiler)
  assert.match(inheritedBase.stdout + inheritedBase.stderr, /TS2322/)
  for (const empty of [{files: []}, {include: []}, {references: []}]) {
    await writeFile(base, JSON.stringify({extends: './tsconfig.shared.json', ...empty}))
    const emptyBase = run(directory, compiler)
    assert.match(emptyBase.stdout + emptyBase.stderr, /TS2322/)
  }
  const parameters = resolve(pkg, 'tsconfig.parameters.json')
  await rename(base, parameters)
  await symlink(parameters, base)
  const linkedBase = run(directory, compiler)
  assert.match(linkedBase.stdout + linkedBase.stderr, /TS2322/)
  await rm(base)
  await rename(parameters, base)
  await writeFile(base, JSON.stringify({compilerOptions: {strict: true}, files: ['src/index.ts']}))
  const executableBase = run(directory, compiler)
  assert.match(executableBase.stderr, /Unregistered compiler project.*tsconfig\.base\.json/)
  await rm(base)
  await rm(shared)
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  const invalid = run(directory, compiler)
  assert.notEqual(invalid.status, 0)
  assert.match(invalid.stdout + invalid.stderr, /TS2322/)
  for (const directive of ['// @ts-nocheck', '/// @ts-nocheck', '#!/usr/bin/env node\n// @ts-nocheck']) {
    await writeFile(resolve(pkg, 'src/index.ts'), directive + '\nexport const value: string = 1\n')
    const unchecked = run(directory, compiler)
    assert.notEqual(unchecked.status, 0)
    assert.match(unchecked.stderr, /Package source disables typechecking.*index\.ts/)
  }
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const marker = "// @ts-nocheck"; export const value: string = 1\n')
  const literal = run(directory, compiler)
  assert.match(literal.stdout + literal.stderr, /TS2322/)
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const value = 1\n')
  await writeFile(resolve(pkg, 'src/ambient.d.ts'), '// @ts-nocheck\ndeclare const value: string = 1\n')
  const declaration = run(directory, compiler)
  assert.match(declaration.stderr, /Package source disables typechecking.*ambient\.d\.ts/)
  await writeFile(resolve(pkg, 'src/ambient.d.ts'), 'declare const ignored: string\n')
  const unregisteredDeclaration = run(directory, compiler)
  assert.match(unregisteredDeclaration.stderr, /Unregistered authored TypeScript.*ambient\.d\.ts/)
  await rm(resolve(pkg, 'src/ambient.d.ts'))
  await writeFile(resolve(pkg, 'src/helper.js'), 'export const count = /** @type {string} */ (1)\n')
  await writeFile(resolve(pkg, 'src/index.ts'), "import {count} from './helper.js'\nexport const value = count\n")
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, allowJs: true, checkJs: false, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  const javascript = run(directory, compiler)
  assert.notEqual(javascript.status, 0)
  assert.match(javascript.stderr, /JavaScript package source.*helper\.js/)
  await rm(resolve(pkg, 'src/helper.js'))
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const value = 1\n')
  const permissive = run(directory, compiler)
  assert.match(permissive.stderr, /Package declaration project must not enable allowJs/)
  await writeFile(resolve(pkg, 'tsconfig.json'), JSON.stringify({compilerOptions: {strict: true, noEmit: true, module: 'NodeNext', target: 'ES2022', types: []}, files: ['src/index.ts']}))
  await writeFile(resolve(pkg, 'src/orphan.ts'), 'export const orphan = 1\n')
  const orphan = run(directory, compiler)
  assert.notEqual(orphan.status, 0)
  assert.match(orphan.stderr, /Unregistered authored TypeScript.*orphan\.ts/)
  await rm(resolve(pkg, 'src/orphan.ts'))
  await mkdir(resolve(pkg, 'src/dist'))
  await writeFile(resolve(pkg, 'src/dist/hidden.ts'), 'export const hidden = 1\n')
  const hidden = run(directory, compiler)
  assert.match(hidden.stderr, /Unregistered authored TypeScript.*hidden\.ts/)
  await rm(resolve(pkg, 'src/dist'), {recursive: true})
  await rename(resolve(pkg, 'tsconfig.json'), resolve(pkg, 'compiler.json'))
  await symlink(resolve(pkg, 'compiler.json'), resolve(pkg, 'tsconfig.json'))
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const value: string = 1\n')
  const ownedLink = run(directory, compiler)
  assert.match(ownedLink.stdout + ownedLink.stderr, /TS2322/)
  await rm(resolve(pkg, 'tsconfig.json'))
  await rename(resolve(pkg, 'compiler.json'), resolve(pkg, 'tsconfig.json'))
  await writeFile(resolve(pkg, 'src/value.ts'), 'export const count: number = 1\n')
  await symlink(resolve(pkg, 'src/value.ts'), resolve(pkg, 'src/alias.ts'))
  await writeFile(resolve(pkg, 'src/index.ts'), "import {count} from './alias.js'\nexport const value: string = count\n")
  const ownedSource = run(directory, compiler)
  assert.match(ownedSource.stdout + ownedSource.stderr, /TS2322/)
  await rm(resolve(pkg, 'src/alias.ts'))
  await rm(resolve(pkg, 'src/value.ts'))
  await writeFile(resolve(pkg, 'src/index.ts'), 'export const value = 1\n')
  await symlink(resolve(pkg, 'src'), resolve(pkg, 'src/cycle'))
  const cycle = run(directory, compiler)
  assert.match(cycle.stderr, /Package symlink cycle/)
  await rm(resolve(pkg, 'src/cycle'))
  await writeFile(resolve(directory, 'outside.ts'), 'export const outside = 1\n')
  await symlink(resolve(directory, 'outside.ts'), resolve(pkg, 'src/link.ts'))
  const link = run(directory, compiler)
  assert.notEqual(link.status, 0)
  assert.match(link.stderr, /Package symlink escapes package.*link\.ts/)
  await rm(resolve(pkg, 'src/link.ts'))
  await writeFile(resolve(pkg, 'tsconfig.unregistered.json'), JSON.stringify({files: ['src/index.ts']}))
  const project = run(directory, compiler)
  assert.notEqual(project.status, 0)
  assert.match(project.stderr, /Unregistered compiler project.*tsconfig\.unregistered\.json/)
})
