import {test} from 'node:test'
import assert from 'node:assert/strict'
import {spawn} from 'node:child_process'
import {chromium} from 'playwright'

const base = 'http://127.0.0.1:4329'
test('a researcher edits and downloads the current study metadata', async () => {
  const server = spawn(process.execPath, ['../../artifacts/web/dist/server/entry.mjs'], {
    cwd: new URL('..', import.meta.url), env: {...process.env, HOST: '127.0.0.1', PORT: '4329'}, stdio: 'ignore',
  })
  let browser
  try {
    for (let attempt = 0; ; attempt++) {
      try { if ((await fetch(base)).ok) break } catch {}
      if (attempt === 100 || server.exitCode !== null) throw new Error('Built application did not start')
      await new Promise(resolve => setTimeout(resolve, 100))
    }
    browser = await chromium.launch({headless: true})
    const page = await browser.newPage({acceptDownloads: true})
    page.setDefaultTimeout(5000)
    const externalRequests: string[] = []
    const fontResponses: number[] = []
    page.on('response', response => {if (response.url().includes('/visual-framework/') && response.url().endsWith('.woff')) fontResponses.push(response.status())})
    page.on('request', request => {if (/^https?:/.test(request.url()) && !request.url().startsWith(base)) externalRequests.push(request.url())})
    const stylesheet = page.waitForResponse(response => response.url() === base + '/visual-framework/css/styles.css')
    await page.goto(base)
    assert.equal((await stylesheet).status(), 200)
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.evaluate(() => document.fonts.check('16px \"IBM Plex Sans\"')), true)
    assert.ok(fontResponses.length > 0 && fontResponses.every(status => status === 200))
    const create = page.getByRole('button', {name: 'Create study'})
    assert.match(await create.getAttribute('class') ?? '', /\bvf-button--primary\b/)
    assert.equal(await create.evaluate(button => getComputedStyle(button).borderRadius), '0px')
    const restingShadow = await create.evaluate(button => getComputedStyle(button).boxShadow)
    await create.focus()
    assert.notEqual(await create.evaluate(button => getComputedStyle(button).boxShadow), restingShadow)
    await create.click()
    await page.getByLabel('Study title').fill('Microscopy study')
    await page.getByLabel('Description').fill('An example study')
    await page.getByLabel('License').fill('https://creativecommons.org/licenses/by/4.0/')
    await page.getByLabel('Funding statement').fill('Supported by a research fund')
    const navigate = async (name: string) => {
      await page.getByRole('navigation', {name: 'Study sections', exact: true}).getByRole('link', {name, exact: true}).click()
      await page.locator('.section-heading').waitFor()
      await page.waitForFunction(label => document.activeElement?.classList.contains('section-heading') && document.activeElement.textContent?.includes(label), name === 'Contributors' ? 'Contributors and author order' : name)
    }
    await navigate('Affiliations')
    const breadcrumb = page.getByRole('navigation', {name: 'Breadcrumb', exact: true})
    assert.equal(await breadcrumb.getByRole('link', {name: 'Workspace'}).getAttribute('href'), '#study')
    assert.equal(await breadcrumb.locator('[aria-current=page]').innerText(), 'Affiliations')
    await breadcrumb.getByRole('link', {name: 'Workspace'}).click()
    await page.getByRole('heading', {name: 'Study details'}).waitFor()
    assert.equal(await breadcrumb.locator('[aria-current=page]').innerText(), 'Study details')
    await navigate('Affiliations')
    await page.getByRole('button', {name: 'Add affiliation'}).click()
    await page.getByLabel('Affiliation name 1').fill('Shared institute')
    await page.getByRole('button', {name: 'Add affiliation'}).click()
    await page.getByLabel('Affiliation name 2').fill('Shared institute')
    await navigate('Contributors')
    await page.getByRole('button', {name: 'Add contributor'}).click()
    await page.getByRole('button', {name: 'Add contributor'}).click()
    await page.getByLabel('Contributor name 1').fill('First researcher')
    await page.getByLabel('Contributor name 2').fill('Second researcher')
    await page.getByRole('group', {name: 'Affiliations for contributor 1'}).getByRole('checkbox', {name: 'Shared institute (#entity-1)', exact: true}).check()
    await page.getByRole('group', {name: 'Affiliations for contributor 2'}).getByRole('checkbox', {name: 'Shared institute (#entity-1)', exact: true}).check()
    await navigate('Affiliations')
    assert.equal(await page.getByLabel('Affiliation name 1').inputValue(), 'Shared institute')
    await page.getByRole('button', {name: 'Delete affiliation 1'}).click()
    assert.match(await page.getByRole('alert').innerText(), /2 references/i)
    await navigate('Contributors')
    assert.equal(await page.getByLabel('Contributor name 1').inputValue(), 'First researcher')
    await page.getByRole('button', {name: 'Move contributor 2 up'}).focus()
    await page.keyboard.press('Enter')
    await navigate('Publications')
    await page.getByRole('button', {name: 'Add publication'}).click()
    await page.getByLabel('Publication title 1').fill('A published study')
    await page.getByLabel('Publication DOI 1').fill('10.1234/example')
    await navigate('Funding')
    await page.getByRole('button', {name: 'Add funding body'}).click()
    await page.getByLabel('Funding body name 1').fill('Research fund')
    await page.getByRole('button', {name: 'Add funding body'}).click()
    await page.getByLabel('Funding body name 2').fill('Research fund')
    await page.getByRole('button', {name: 'Add grant'}).click()
    await page.getByLabel('Grant identifier 1').fill('award-7')
    const funderChoices = page.getByRole('group', {name: 'Funding bodies for grant 1'}).locator('label')
    const funderLabels = await funderChoices.allTextContents()
    assert.equal(new Set(funderLabels).size, 2, 'Duplicate funder names must have distinct labels')
    await funderChoices.first().getByRole('checkbox').check()
    await navigate('Export metadata')
    assert.equal(await page.getByLabel('Grant identifier 1').count(), 0)
    await page.goBack()
    assert.equal(await page.getByLabel('Grant identifier 1').inputValue(), 'award-7')
    await page.goForward()
    await page.getByRole('heading', {name: 'Export metadata'}).waitFor()
    await page.getByText('This export does not include file_list.tsv.', {exact: false}).waitFor()
    await navigate('Specimens')
    await page.getByRole('button', {name: 'Add specimen'}).click()
    const label = page.getByRole('textbox', {name:'Specimen label 1', description:'For this draft; the label is not included in metadata export.'})
    assert.equal(await label.count(), 1)
    const emptySamples = page.getByRole('group', {name:'Biosamples for specimen 1'})
    assert.equal(await emptySamples.getByRole('link', {name:'Biosamples'}).getAttribute('href'), '#biosamples')
    assert.equal(await page.getByRole('group', {name:'Preparation protocols for specimen 1'}).getByRole('link', {name:'Protocols'}).getAttribute('href'), '#protocols')
    await emptySamples.getByRole('link', {name:'Biosamples'}).click()
    await page.getByRole('heading', {name:'Biosamples', exact:true}).waitFor()
    await page.getByRole('button', {name: 'Add biosample'}).click()
    await page.getByRole('button', {name: 'Add biosample'}).click()
    await page.getByLabel('Biosample name 1').fill('Biosample A')
    await page.getByLabel('Biosample name 2').fill('Biosample B')
    await navigate('Specimens')
    await page.getByRole('button', {name: 'Add specimen'}).click()
    await page.getByLabel('Specimen label 1').fill('Specimen A')
    await page.getByLabel('Specimen label 2').fill('Specimen B')
    const specimenA = (await page.getByRole('group', {name: 'Specimen 1', exact: true}).getAttribute('id'))?.replace(/^scientific-record-/, '')
    const specimenB = (await page.getByRole('group', {name: 'Specimen 2', exact: true}).getAttribute('id'))?.replace(/^scientific-record-/, '')
    assert.ok(specimenA && specimenB && specimenA !== specimenB)
    await navigate('Protocols')
    await page.getByRole('button', {name: 'Add preparation protocol'}).click()
    await page.getByLabel('Preparation protocol name 1').fill('Shared preparation')
    await page.getByRole('button', {name: 'Add acquisition protocol'}).click()
    await page.getByRole('button', {name: 'Add acquisition protocol'}).click()
    await page.getByLabel('Acquisition protocol name 1').fill('Acquisition A')
    await page.getByLabel('Acquisition protocol name 2').fill('Acquisition B')
    await navigate('Specimens')
    await page.getByRole('group', {name: 'Biosamples for specimen 1'}).getByRole('checkbox', {name: 'Biosample A'}).check()
    await page.getByRole('group', {name: 'Biosamples for specimen 2'}).getByRole('checkbox', {name: 'Biosample B'}).check()
    await page.getByRole('group', {name: 'Preparation protocols for specimen 1'}).getByRole('checkbox', {name: 'Shared preparation'}).check()
    await page.getByRole('group', {name: 'Preparation protocols for specimen 2'}).getByRole('checkbox', {name: 'Shared preparation'}).check()
    await navigate('Protocols')
    const dependents = page.getByRole('group', {name: 'Dependents of preparation protocol 1'})
    assert.match(await dependents.innerText(), /2 records/)
    const dependentLink = dependents.getByRole('link', {name: 'Specimen A'})
    const recordHash = await dependentLink.getAttribute('href')
    assert.equal(recordHash, `#specimens/${encodeURIComponent(specimenA)}`)
    await dependentLink.focus()
    await page.keyboard.press('Enter')
    await page.waitForFunction(id => document.activeElement?.id === `scientific-record-${id}`, specimenA)
    await page.goBack()
    await page.getByRole('heading', {name:'Protocols', exact:true}).waitFor()
    await page.goForward()
    await page.waitForFunction(id => document.activeElement?.id === `scientific-record-${id}`, specimenA)
    assert.equal(new URL(page.url()).hash,recordHash)
    await navigate('Protocols')
    await page.evaluate(hash => {window.location.hash = hash}, recordHash!)
    await page.waitForFunction(id => document.activeElement?.id === `scientific-record-${id}`, specimenA)
    await navigate('Protocols')
    assert.equal(await page.getByRole('button', {name: 'Delete preparation protocol 1'}).isDisabled(), true)
    await navigate('Datasets')
    await page.getByRole('button', {name: 'Add dataset'}).click()
    await page.getByRole('button', {name: 'Add dataset'}).click()
    await page.getByLabel('Dataset name 1').fill('Dataset A')
    await page.getByLabel('Dataset name 2').fill('Dataset B')
    await page.getByLabel('Specimen for dataset 1').selectOption(specimenA)
    await page.getByLabel('Specimen for dataset 2').selectOption(specimenB)
    await page.getByRole('group', {name: 'Acquisition protocols for dataset 1'}).getByRole('checkbox', {name: 'Acquisition A'}).check()
    await page.getByRole('group', {name: 'Acquisition protocols for dataset 2'}).getByRole('checkbox', {name: 'Acquisition B'}).check()
    await navigate('Specimens')
    await page.getByLabel('Specimen label 1').fill('Renamed specimen A')
    assert.equal(await page.getByRole('group', {name: 'Specimen 1', exact: true}).getAttribute('id'), `scientific-record-${specimenA}`)
    await navigate('Datasets')
    assert.equal(await page.getByLabel('Specimen for dataset 1').inputValue(), specimenA)
    await navigate('Export metadata')
    const download = page.waitForEvent('download')
    await page.getByRole('button', {name: 'Download metadata'}).click()
    const file = await download
    assert.equal(file.suggestedFilename(), 'ro-crate-metadata.json')
    const chunks = []
    for await (const chunk of await file.createReadStream()) chunks.push(chunk)
    const metadata = JSON.parse(Buffer.concat(chunks).toString()) as {'@graph': Array<Record<string, unknown>>}
    const study = metadata['@graph'].find(item => item['@id'] === './')
    assert.ok(study)
    assert.equal(study.name, 'Microscopy study')
    assert.equal(study.description, 'An example study')
    assert.equal(study.license, 'https://creativecommons.org/licenses/by/4.0/')
    assert.equal(study.fundingStatement, 'Supported by a research fund')
    const byId = new Map(metadata['@graph'].map(node => [node['@id'], node]))
    const sampleA = metadata['@graph'].find(node => node.name === 'Biosample A')!
    const sampleB = metadata['@graph'].find(node => node.name === 'Biosample B')!
    const prep = metadata['@graph'].find(node => node.name === 'Shared preparation')!
    const acquisitionA = metadata['@graph'].find(node => node.name === 'Acquisition A')!
    const acquisitionB = metadata['@graph'].find(node => node.name === 'Acquisition B')!
    const datasetA = metadata['@graph'].find(node => node.name === 'Dataset A')!
    const datasetB = metadata['@graph'].find(node => node.name === 'Dataset B')!
    assert.deepEqual(byId.get(specimenA)?.biologicalEntity,[{'@id':sampleA['@id']}])
    assert.deepEqual(byId.get(specimenB)?.biologicalEntity,[{'@id':sampleB['@id']}])
    assert.deepEqual(byId.get(specimenA)?.imagingPreparationProtocol,[{'@id':prep['@id']}])
    assert.deepEqual(byId.get(specimenB)?.imagingPreparationProtocol,[{'@id':prep['@id']}])
    assert.deepEqual(datasetA.associatedSpecimen,{'@id':specimenA})
    assert.deepEqual(datasetB.associatedSpecimen,{'@id':specimenB})
    assert.deepEqual(datasetA.associatedImageAcquisitionProtocol,[{'@id':acquisitionA['@id']}])
    assert.deepEqual(datasetB.associatedImageAcquisitionProtocol,[{'@id':acquisitionB['@id']}])
    assert.equal(Object.hasOwn(byId.get(specimenA)!,'label'),false)
    assert.equal(Object.hasOwn(byId.get(specimenA)!,'name'),false)
    const people = study.author as Array<{'@id': string}>
    assert.deepEqual(people.map(ref => byId.get(ref['@id'])?.name), ['Second researcher', 'First researcher'])
    const institution = metadata['@graph'].find(node => node.name === 'Shared institute')
    assert.ok(institution)
    for (const person of people) assert.deepEqual(byId.get(person['@id'])?.memberOf, [{'@id': institution['@id']}])
    const publications = study.relatedPublication as Array<{'@id': string}>
    assert.equal(byId.get(publications[0]['@id'])?.doi, '10.1234/example')
    const funding = study.funding as Array<{'@id': string}>
    const grant = byId.get(funding[0]['@id'])
    assert.equal(grant?.identifier, 'award-7')
    const body = metadata['@graph'].find(node => node.name === 'Research fund')
    assert.ok(body)
    assert.deepEqual(grant?.funder, [{'@id': body['@id']}])
    assert.match(await page.getByRole('status').innerText(), /local recovery/i)
    await page.setViewportSize({width: 900, height: 844})
    const mediumGuidance = page.getByRole('button', {name: /study guidance/i})
    if (await mediumGuidance.getAttribute('aria-expanded') === 'false') await mediumGuidance.click()
    const panel = await page.locator('#study-guidance').boundingBox()
    const heading = await page.getByRole('heading', {name: 'Microscopy study'}).boundingBox()
    assert.ok(panel && heading && panel.y + panel.height <= heading.y, 'Expanded guidance must not overlap the editor')
    await navigate('Study details')
    assert.equal(await page.getByLabel('Study title').inputValue(), 'Microscopy study')
    await page.getByLabel('Study title').click({timeout: 3000})
    await page.getByRole('button', {name: /study guidance/i}).click()
    await page.setViewportSize({width: 390, height: 844})
    await page.getByRole('navigation', {name: 'Mobile study sections'}).getByRole('link', {name: 'Contributors', exact: true}).click()
    assert.equal(await page.getByLabel('Contributor name 1').inputValue(), 'Second researcher')
    assert.equal(await page.getByLabel('Study title').count(), 0)
    await page.evaluate(() => {window.location.hash = '#unknown-section'})
    await page.getByLabel('Study title').waitFor()
    assert.equal(await page.getByLabel('Study title').inputValue(), 'Microscopy study')
    const guidance = page.getByRole('button', {name: /study guidance/i})
    assert.equal(await guidance.getAttribute('aria-expanded'), 'false')
    await guidance.click()
    assert.equal(await guidance.getAttribute('aria-expanded'), 'true')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    assert.deepEqual(externalRequests, [])
  } finally {
    await browser?.close()
    server.kill()
  }
})
