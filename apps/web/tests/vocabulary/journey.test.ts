import {test} from 'node:test'
import assert from 'node:assert/strict'
import {spawn} from 'node:child_process'
import {chromium} from 'playwright'
import {applyChange, createDraft, materializeDraft, type DraftChange} from '@bijux/ro-crate-creator'

const base = 'http://127.0.0.1:4337'
test('a researcher assigns and checks current vocabulary assertions', async () => {
  const server = spawn(process.execPath,['../../artifacts/web/dist/server/entry.mjs'],{cwd:new URL('../..',import.meta.url),env:{...process.env,HOST:'127.0.0.1',PORT:'4337'},stdio:'ignore'})
  let browser
  try {
    for (let attempt = 0;; attempt++) {
      try {if ((await fetch(base)).ok) break} catch {}
      if (attempt === 100 || server.exitCode !== null) throw Error('Built app did not start')
      await new Promise(resolve => setTimeout(resolve,100))
    }
    assert.equal((await fetch(base + '/api/vocabulary?kind=unknown&mode=exact&value=https%3A%2F%2Fexample.org')).status,400)
    browser = await chromium.launch({headless:true})
    const page = await browser.newPage({acceptDownloads:true}); page.setDefaultTimeout(5000)
    let delayNext = false
    await page.route('**/api/vocabulary?*', async route => {
      if (delayNext) {delayNext = false; await new Promise(resolve => setTimeout(resolve,250))}
      const url = new URL(route.request().url()), value = url.searchParams.get('value')
      const body = url.searchParams.get('mode') === 'search' ? {status:'ok',suggestions:[{identifier:'NCBITaxon:9606',label:'Homo sapiens'}]} : value === 'NCBITaxon:9606' ? {status:'found',term:{source:'fixture',identifier:value,label:'Homo sapiens',synonyms:['human'],obsolete:false,retrievedAt:'2026-11-25T00:00:00Z'}} : value === 'FBbi:99999999' ? {status:'not-found',identifier:value,source:'fixture',retrievedAt:'2026-11-25T00:00:00Z'} : value === 'FBbi:00000001' ? {status:'found',term:{source:'fixture',identifier:value,label:'old method',synonyms:[],obsolete:true,retrievedAt:'2026-11-25T00:00:00Z'}} : {status:'unavailable'}
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)})
    })
    page.on('dialog', dialog => dialog.accept())
    await page.goto(base); await page.getByRole('button',{name:'Create study'}).click()
    const nav = page.getByRole('navigation',{name:'Study sections',exact:true})
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    await page.getByRole('button',{name:'Add biosample'}).click()
    const add = page.getByRole('group',{name:'Add organism to biosample 1'})
    await add.getByLabel('Add organism to biosample 1 label').fill('Drosophila melanogaster')
    await nav.getByRole('link',{name:'Protocols',exact:true}).click()
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    assert.equal(await add.getByLabel('Add organism to biosample 1 label').inputValue(),'Drosophila melanogaster')
    await page.getByText('Recovery copy saved in this browser.',{exact:false}).first().waitFor()
    const recoveryId = await page.evaluate(async () => {
      const db = await new Promise<IDBDatabase>((resolve,reject) => {const request = indexedDB.open('bijux-draft-recovery'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error)})
      const records = await new Promise<Array<{id:string;backup:string}>>(resolve => {const request = db.transaction('drafts').objectStore('drafts').getAll(); request.onsuccess = () => resolve(request.result)})
      db.close()
      return records.find(record => JSON.parse(record.backup).pendingTerms?.[0]?.label === 'Drosophila melanogaster')?.id
    })
    assert.ok(recoveryId)
    await nav.getByRole('link',{name:'Validate crate',exact:true}).click()
    await page.getByText('Apply or discard pending vocabulary input before validation.',{exact:false}).waitFor()
    assert.equal(await page.getByRole('button',{name:'Continue',exact:true}).isDisabled(),true)
    await nav.getByRole('link',{name:'Export metadata',exact:true}).click()
    await page.getByRole('button',{name:'Download metadata'}).click()
    await page.getByText('Apply or discard unfinished vocabulary input before export.',{exact:false}).waitFor()
    await nav.getByRole('link',{name:'Local recovery',exact:true}).click()
    const backupDownload = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download editable backup'}).click()
    const backupStream = await (await backupDownload).createReadStream(); let backup = ''
    for await (const chunk of backupStream) backup += chunk.toString()
    const envelope = JSON.parse(backup)
    assert.equal(envelope.version,2)
    assert.equal(envelope.pendingTerms[0].label,'Drosophila melanogaster')
    await page.reload()
    await nav.getByRole('link',{name:'Local recovery',exact:true}).click()
    await page.waitForFunction(() => document.querySelectorAll('#recovery-copy option').length > 1)
    await page.locator('#recovery-copy').selectOption(recoveryId)
    await page.getByRole('button',{name:'Restore selected copy'}).click()
    await page.getByText('Recovery opened.',{exact:false}).first().waitFor()
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    assert.equal(await add.getByLabel('Add organism to biosample 1 label').inputValue(),'Drosophila melanogaster')
    await nav.getByRole('link',{name:'Local recovery',exact:true}).click()
    await page.getByLabel('Open a full backup').setInputFiles({name:'study-backup.json',mimeType:'application/json',buffer:Buffer.from(backup)})
    await page.getByText('Recovery opened.',{exact:false}).first().waitFor()
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    assert.equal(await add.getByLabel('Add organism to biosample 1 label').inputValue(),'Drosophila melanogaster')
    await add.getByLabel('Add organism to biosample 1 identifier').fill('NCBITaxon:9606')
    await add.getByRole('button',{name:'Apply identifier and label for Add organism to biosample 1'}).click()
    const organism = page.getByRole('group',{name:'Organism 1 for biosample 1'})
    await organism.getByRole('button',{name:'Check current value for Organism 1 for biosample 1'}).click()
    await organism.getByText(/do not match/).waitFor()
    await organism.getByLabel('Organism 1 for biosample 1 label').fill('Homo sapiens')
    assert.equal(await organism.getByText(/do not match/).count(),0)
    await organism.getByRole('button',{name:'Apply identifier and label for Organism 1 for biosample 1'}).click()
    await organism.getByRole('button',{name:'Check current value for Organism 1 for biosample 1'}).click()
    await organism.getByText(/Verified against/).waitFor()
    delayNext = true
    await organism.getByRole('button',{name:'Check current value for Organism 1 for biosample 1'}).click()
    await organism.getByLabel('Organism 1 for biosample 1 label').fill('human')
    await page.waitForTimeout(350)
    assert.equal(await organism.getByText(/Verified against/).count(),0)
    assert.equal(await organism.getByText(/Verified against/).count(),0)
    await organism.getByRole('button',{name:'Search suggestions for Organism 1 for biosample 1'}).click()
    await organism.getByText(/Suggestions are not verified/).waitFor()
    assert.equal(await organism.getByText(/Verified against/).count(),0)
    await organism.getByRole('button',{name:'Discard changes for Organism 1 for biosample 1'}).click()
    await nav.getByRole('link',{name:'Protocols',exact:true}).click()
    await page.getByRole('button',{name:'Add acquisition protocol'}).click()
    const imaging = page.getByRole('group',{name:'Imaging method for acquisition protocol 1'})
    await imaging.getByLabel('Imaging method for acquisition protocol 1 label').fill('unknown method')
    await imaging.getByLabel('Imaging method for acquisition protocol 1 identifier').fill('FBbi:99999999')
    await imaging.getByRole('button',{name:'Apply identifier and label for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByRole('button',{name:'Check current value for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByText(/Identifier not found/).waitFor()
    await imaging.getByLabel('Imaging method for acquisition protocol 1 identifier').fill('FBbi:00000001')
    await imaging.getByLabel('Imaging method for acquisition protocol 1 label').fill('old method')
    await imaging.getByRole('button',{name:'Apply identifier and label for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByRole('button',{name:'Check current value for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByText(/marks this term obsolete/).waitFor()
    await imaging.getByLabel('Imaging method for acquisition protocol 1 identifier').fill('FBbi:00000002')
    await imaging.getByLabel('Imaging method for acquisition protocol 1 label').fill('unknown method')
    await imaging.getByRole('button',{name:'Apply identifier and label for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByRole('button',{name:'Check current value for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByText(/service unavailable/).waitFor()
    await imaging.getByLabel('Imaging method for acquisition protocol 1 identifier').fill('')
    await imaging.getByRole('button',{name:'Apply identifier and label for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByRole('button',{name:'Check current value for Imaging method for acquisition protocol 1'}).click()
    await imaging.getByText(/Descriptive text/).waitFor()
    await nav.getByRole('link',{name:'Export metadata',exact:true}).click()
    const download = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download metadata'}).click()
    const bytes = await (await download).createReadStream(); let content = ''
    for await (const chunk of bytes) content += chunk.toString()
    const graph = JSON.parse(content)['@graph'] as Array<Record<string,unknown>>
    const taxon = graph.find(node => node['@id'] === 'http://purl.obolibrary.org/obo/NCBITaxon_9606')
    assert.equal(taxon?.scientificName,'Homo sapiens')
    const protocol = graph.find(node => Array.isArray(node['@type']) && node['@type'].includes('bia:ImageAcquisitionProtocol'))
    assert.deepEqual(protocol?.imagingMethodName,['unknown method'])
    assert.deepEqual(protocol?.fbbiId,[])
    let source = createDraft()
    const step = (command:DraftChange) => {const result = applyChange(source,command); if (result.status !== 'applied') throw Error('import fixture'); source = result.draft; return result.entityId}
    step({type:'add-study'})
    const sample = step({type:'add-entity',kind:'biosample'})
    step({type:'assign-organism',entityId:sample,previousId:null,identifier:'NCBITaxon:9606',label:'Drosophila melanogaster'})
    const exported = materializeDraft(source); if (exported.status !== 'materialized') throw Error()
    const imported = JSON.parse(exported.files.get('ro-crate-metadata.json') as string)
    imported['@context'][1].custom = {'@id':'https://example.org/custom'}
    imported['@graph'].find((node:{'@id':string}) => node['@id'] === sample).custom = 'preserved'
    await nav.getByRole('link',{name:'Local recovery',exact:true}).click()
    await page.getByLabel('Import metadata files').setInputFiles({name:'ro-crate-metadata.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))})
    await page.getByText('Recovery opened.',{exact:false}).first().waitFor()
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    const importedTerm = page.getByRole('group',{name:'Organism 1 for biosample 1'})
    assert.equal(await importedTerm.getByLabel('Organism 1 for biosample 1 identifier').inputValue(),'NCBITaxon:9606')
    await importedTerm.getByRole('button',{name:'Check current value for Organism 1 for biosample 1'}).click()
    await importedTerm.getByText(/do not match/).waitFor()
    await importedTerm.getByLabel('Organism 1 for biosample 1 label').fill('Homo sapiens')
    await importedTerm.getByRole('button',{name:'Apply identifier and label for Organism 1 for biosample 1'}).click()
    await nav.getByRole('link',{name:'Export metadata',exact:true}).click()
    const importedDownload = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download metadata'}).click()
    const importedStream = await (await importedDownload).createReadStream(); let importedText = ''
    for await (const chunk of importedStream) importedText += chunk.toString()
    const importedGraph = JSON.parse(importedText)['@graph'] as Array<Record<string,unknown>>
    assert.equal(importedGraph.find(node => node['@id'] === sample)?.custom,'preserved')
    assert.equal(importedGraph.find(node => node['@id'] === 'http://purl.obolibrary.org/obo/NCBITaxon_9606')?.scientificName,'Homo sapiens')
    await nav.getByRole('link',{name:'Biosamples',exact:true}).click()
    await page.getByRole('button',{name:'Add biosample'}).click()
    const secondNew = page.getByRole('group',{name:'Add organism to biosample 2'})
    await secondNew.getByLabel('Add organism to biosample 2 label').fill('Homo sapiens')
    await secondNew.getByLabel('Add organism to biosample 2 identifier').fill('NCBITaxon:9606')
    await secondNew.getByRole('button',{name:'Apply identifier and label for Add organism to biosample 2'}).click()
    const firstShared = page.getByRole('group',{name:'Organism 1 for biosample 1'})
    const secondShared = page.getByRole('group',{name:'Organism 1 for biosample 2'})
    await firstShared.getByLabel('Organism 1 for biosample 1 label').fill('human')
    await secondShared.getByLabel('Organism 1 for biosample 2 label').fill('human')
    await secondShared.getByRole('button',{name:'Apply identifier and label for Organism 1 for biosample 2'}).click()
    assert.equal(await firstShared.getByRole('button',{name:'Check current value for Organism 1 for biosample 1'}).isDisabled(),true)
    assert.equal(await firstShared.getByRole('button',{name:'Discard changes for Organism 1 for biosample 1'}).isVisible(),true)
    await firstShared.getByRole('button',{name:'Discard changes for Organism 1 for biosample 1'}).click()
  } finally {await browser?.close(); server.kill('SIGTERM')}
})
