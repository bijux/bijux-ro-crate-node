import {test} from 'node:test'
import assert from 'node:assert/strict'
import {spawn} from 'node:child_process'
import {chromium} from 'playwright'
const base = 'http://127.0.0.1:4332'
test('recovery restores pending listings while separate tabs retain separate copies', async () => {
  const server = spawn(process.execPath, ['../../artifacts/web/dist/server/entry.mjs'], {cwd:new URL('..', import.meta.url), env:{...process.env,HOST:'127.0.0.1',PORT:'4332'},stdio:'ignore'})
  let browser
  try {
    for (let attempt = 0;; attempt++) {try {if ((await fetch(base)).ok) break} catch {} if (attempt === 100 || server.exitCode !== null) throw Error('Server did not start'); await new Promise(resolve => setTimeout(resolve,100))}
    browser = await chromium.launch({headless:true})
    const context = await browser.newContext({acceptDownloads:true})
    const page = await context.newPage()
    page.on('dialog', dialog => dialog.accept())
    await page.goto(base)
    await page.getByRole('button',{name:'Create study'}).click()
    await page.getByLabel('Study title').fill('Recovered study')
    await page.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Files',exact:true}).click()
    await page.getByLabel('List files',{exact:true}).setInputFiles({name:'image.tif',mimeType:'image/tiff',buffer:Buffer.from('image')})
    await page.getByText('1 pending assignment.',{exact:false}).waitFor()
    await page.waitForFunction(async () => {
      const db = await new Promise<IDBDatabase>((resolve,reject) => {const r = indexedDB.open('bijux-draft-recovery'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error)})
      const records = await new Promise<Array<{id:string;backup:string}>>(resolve => {const r = db.transaction('drafts').objectStore('drafts').getAll(); r.onsuccess = () => resolve(r.result)})
      db.close(); return records.some(record => JSON.parse(record.backup).pending.length === 1)
    })
    const other = await context.newPage(); other.on('dialog', dialog => dialog.accept())
    await other.goto(base)
    await other.getByRole('button',{name:'Create study'}).click()
    await other.getByLabel('Study title').fill('Other tab')
    await other.getByText('Recovery copy saved in this browser.',{exact:false}).first().waitFor()
    await page.reload()
    await page.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Local recovery',exact:true}).click()
    const options = page.locator('#recovery-copy option')
    await page.waitForFunction(() => document.querySelectorAll('#recovery-copy option').length === 3)
    assert.equal(await options.count(),3)
    const copyId = await page.evaluate(async () => {
      const db = await new Promise<IDBDatabase>(resolve => {const r = indexedDB.open('bijux-draft-recovery'); r.onsuccess = () => resolve(r.result)})
      const records = await new Promise<Array<{id:string;backup:string}>>(resolve => {const r = db.transaction('drafts').objectStore('drafts').getAll(); r.onsuccess = () => resolve(r.result)})
      db.close(); return records.find(record => JSON.parse(record.backup).pending.length === 1)!.id
    })
    await page.locator('#recovery-copy').selectOption(copyId)
    await page.getByRole('button',{name:'Restore selected copy'}).click()
    await page.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Files',exact:true}).click()
    await page.getByText('1 pending assignment.',{exact:false}).waitFor()
    assert.equal(await page.locator('td').filter({hasText:'image.tif'}).count(),1)
    await page.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Study details',exact:true}).click()
    assert.equal(await page.getByLabel('Study title').inputValue(),'Recovered study')
    await page.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Local recovery',exact:true}).click()
    const download = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download editable backup'}).click()
    assert.equal((await download).suggestedFilename(),'study-backup.json')
    await page.getByLabel('Import metadata files').setInputFiles({name:'ro-crate-metadata.json',mimeType:'application/json',buffer:Buffer.from('{"@context":"https://example.com/unsupported","@graph":[]}')})
    const readonlyDownload = page.waitForEvent('download')
    await page.getByRole('button',{name:'Download read-only backup'}).click()
    assert.equal((await readonlyDownload).suggestedFilename(),'read-only-backup.json')
    assert.equal(await page.getByRole('heading',{name:'Recovered study'}).count(),1)
    const denied = await browser.newContext({acceptDownloads:true})
    await denied.addInitScript(() => Object.defineProperty(window, 'indexedDB', {get() {throw new DOMException('Denied','SecurityError')}}))
    const deniedPage = await denied.newPage()
    await deniedPage.goto(base)
    await deniedPage.getByRole('button',{name:'Create study'}).click()
    await deniedPage.getByLabel('Study title').fill('Unsaved work')
    await deniedPage.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Local recovery',exact:true}).click()
    await deniedPage.getByText(/Browser recovery unavailable|Recovery could not save/).first().waitFor()
    const safeDownload = deniedPage.waitForEvent('download')
    await deniedPage.getByRole('button',{name:'Download editable backup'}).click()
    assert.equal((await safeDownload).suggestedFilename(),'study-backup.json')
    assert.equal(await deniedPage.getByRole('heading',{name:'Unsaved work'}).count(),1)
    await denied.close()
    const quota = await browser.newContext({acceptDownloads:true})
    await quota.addInitScript(() => {
      IDBObjectStore.prototype.put = function () {throw new DOMException('Storage quota exceeded','QuotaExceededError')}
    })
    const quotaPage = await quota.newPage()
    await quotaPage.goto(base)
    await quotaPage.getByRole('button',{name:'Create study'}).click()
    await quotaPage.getByLabel('Study title').fill('Quota work')
    await quotaPage.getByText('Recovery could not save:',{exact:false}).first().waitFor()
    await quotaPage.locator('aside[aria-label="Study navigation"]').getByRole('link',{name:'Local recovery',exact:true}).click()
    const quotaDownload = quotaPage.waitForEvent('download')
    await quotaPage.getByRole('button',{name:'Download editable backup'}).click()
    assert.equal((await quotaDownload).suggestedFilename(),'study-backup.json')
    assert.equal(await quotaPage.getByRole('heading',{name:'Quota work'}).count(),1)
    await quota.close()
    await context.close()
  } finally {await browser?.close(); server.kill()}
})
